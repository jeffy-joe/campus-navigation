export function getAllSearchableLocations() {
  const locations: { id: string; name: string; floorNumber: number; floorCode: string; floorName: string; category: string; code?: string }[] = [];
  
  CAMPUS_FLOORS.forEach(floor => {
    floor.rooms.forEach(room => {
      if (!locations.some(l => l.id === room.id)) {
        locations.push({
          id: room.id,
          name: room.name,
          floorCode: floor.code,
          floorNumber: floor.number,
          floorName: floor.name,
          category: room.category,
          code: room.code
        });
      }
    });
  });

  return locations;
}
